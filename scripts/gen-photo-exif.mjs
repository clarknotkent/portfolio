// Reads EXIF from the photography images once, at build time, and writes it to
// src/lib/photo-exif.ts as a plain object.
//
// The lightbox used to ship the `exifr` parser to every visitor (~128 KB in a
// shared chunk) and re-fetch each full-size image to parse it on open. The data
// is static, so it belongs in the bundle as data, not as a parser plus a fetch.

import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import exifr from "exifr";

const DIR = join(process.cwd(), "public", "images", "photography");
const OUT = join(process.cwd(), "src", "lib", "photo-exif.ts");

const entries = {};
for (const file of readdirSync(DIR).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort()) {
  const data = await exifr.parse(join(DIR, file)).catch(() => null);
  if (!data) continue;
  const record = {};
  if (data.ISO) record.iso = data.ISO;
  if (data.ExposureTime) record.exposureTime = data.ExposureTime;
  if (data.FNumber) record.fNumber = data.FNumber;
  if (data.FocalLength) record.focalLength = Math.round(data.FocalLength);
  if (data.DateTimeOriginal) record.dateTaken = new Date(data.DateTimeOriginal).toISOString();
  if (Object.keys(record).length) entries[`/images/photography/${file}`] = record;
}

const body = Object.entries(entries)
  .map(([k, v]) => `  "${k}": ${JSON.stringify(v)},`)
  .join("\n");

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-photo-exif.mjs — do not edit by hand.
// Run \`npm run exif\` after adding or replacing photography.

export interface PhotoExif {
  iso?: number;
  exposureTime?: number;
  fNumber?: number;
  focalLength?: number;
  /** ISO 8601. */
  dateTaken?: string;
}

export const photoExif: Record<string, PhotoExif> = {
${body}
};
`,
  "utf8",
);

console.log(`photo-exif: ${Object.keys(entries).length} images with EXIF`);
