// Reads the intrinsic pixel dimensions of every image under public/images and
// writes them to src/lib/screenshot-dims.ts.
//
// The gallery needs each image's real aspect ratio so it can frame it exactly
// instead of letterboxing everything into 16:9. The site is a static export, so
// this runs at build time (see the `dims` / `prebuild` scripts in package.json)
// rather than measuring in the browser, which would cause layout shift.
//
// PNG and JPEG headers are parsed directly — no image library needed.

import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const IMAGES_DIR = join(process.cwd(), "public", "images");
const OUT_FILE = join(process.cwd(), "src", "lib", "screenshot-dims.ts");

function pngSize(buf) {
  // 8-byte signature, then the IHDR chunk: 4-byte length, 4-byte type, then w/h.
  if (buf.readUInt32BE(0) !== 0x89504e47) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function jpegSize(buf) {
  if (buf.readUInt16BE(0) !== 0xffd8) return null;
  let offset = 2;
  while (offset < buf.length - 9) {
    if (buf[offset] !== 0xff) {
      offset += 1;
      continue;
    }
    const marker = buf[offset + 1];
    // SOF0-3, SOF5-7, SOF9-11, SOF13-15 carry the frame dimensions.
    // DHT (c4), JPG (c8) and DAC (cc) sit in the same range but do not.
    const isSOF =
      marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker);
    if (isSOF) {
      return { height: buf.readUInt16BE(offset + 5), width: buf.readUInt16BE(offset + 7) };
    }
    offset += 2 + buf.readUInt16BE(offset + 2);
  }
  return null;
}

function measure(file) {
  const buf = readFileSync(file);
  if (buf.length < 24) return null;
  if (file.endsWith(".png")) return pngSize(buf);
  if (/\.jpe?g$/i.test(file)) return jpegSize(buf);
  return null;
}

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, files);
    else if (/\.(png|jpe?g)$/i.test(entry)) files.push(full);
  }
  return files;
}

const dims = {};
let skipped = 0;
for (const file of walk(IMAGES_DIR).sort()) {
  const size = measure(file);
  if (!size || !size.width || !size.height) {
    skipped += 1;
    continue;
  }
  // Keys are the same root-relative paths used in projects.ts.
  const key = "/images/" + relative(IMAGES_DIR, file).split(sep).join("/");
  dims[key] = size;
}

const body = Object.entries(dims)
  .map(([k, v]) => `  "${k}": { width: ${v.width}, height: ${v.height} },`)
  .join("\n");

writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/gen-screenshot-dims.mjs — do not edit by hand.
// Run \`npm run dims\` after adding or replacing images.

export interface ImageDims {
  width: number;
  height: number;
}

export const screenshotDims: Record<string, ImageDims> = {
${body}
};

/** Portrait enough to be a phone capture rather than a desktop one. */
export const PORTRAIT_RATIO = 1.2;

export function isPortrait(src: string): boolean {
  const d = screenshotDims[src];
  if (!d) return false;
  return d.height / d.width >= PORTRAIT_RATIO;
}
`,
  "utf8",
);

console.log(`screenshot-dims: ${Object.keys(dims).length} images measured, ${skipped} skipped`);
